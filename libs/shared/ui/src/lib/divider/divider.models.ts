/** Orientation of the divider rule. Defaults to `'horizontal'`. */
export type SbbDividerOrientation = 'horizontal' | 'vertical';

/** Rule stroke style. Defaults to `'solid'`. */
export type SbbDividerType = 'solid' | 'dashed' | 'dotted';

/**
 * Position of projected content along the rule. Only meaningful when the
 * divider has projected content and is `horizontal`.
 */
export type SbbDividerAlign = 'left' | 'center' | 'right';
